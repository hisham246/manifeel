"""Scene + env config for the USB insertion task, adding a wrist-mounted RGB camera.

Uses the non-Tiled ``Camera`` sensor (via ``CameraCfg``) -- ``TiledCamera`` is known to
hang on RTX 5090 (Blackwell), confirmed earlier this session against the stock AutoMate
visuo-tactile-sensor demo.

Offset/resolution/FOV are ported from the original IsaacGym Preview wrist camera config
(manifeel/manifeel/config/task/TacSLTaskUSB.yaml, the "wrist" entry):
    camera_pose: [[0.045, 0, 0.04], [0.5, 0, 0.866, 0]]   # xyz pos, xyzw quat, rel. panda_hand
    image_size: [256, 256]
    horizontal_fov: 75.0

The rotation convention (ROS vs OpenGL vs world) between IsaacGym Preview's
attach_camera_to_body and Isaac Lab's CameraCfg.OffsetCfg has NOT been visually verified
yet -- flagged for milestone 7 (standalone smoke test with an actual rendered frame).
"""

import math
import pathlib

import isaaclab.sim as sim_utils
from isaaclab.sensors import CameraCfg, ContactSensorCfg
from isaaclab.utils import configclass

from isaaclab_assets.sensors import GELSIGHT_R15_CFG
from isaaclab_contrib.sensors.tacsl_sensor import VisuoTactileSensorCfg
from isaaclab_tasks.contrib.automate.assembly_env_cfg import AssemblyEnvCfg, AssemblySceneCfg, CtrlCfg

from .usb_assembly_tasks_cfg import UsbInsertion

# Solve for the aperture that gives horizontal_fov=75deg at Isaac Lab's default focal_length
# (FOV depends only on the aperture/focal_length ratio, so the absolute unit convention
# doesn't matter as long as both numbers use the same one). wrist and front share the same
# fov/resolution in TacSLTaskUSB.yaml, so this is reused unchanged for both cameras.
_FOCAL_LENGTH = 24.0
_HORIZONTAL_FOV_DEG = 75.0
_HORIZONTAL_APERTURE = 2 * _FOCAL_LENGTH * math.tan(math.radians(_HORIZONTAL_FOV_DEG) / 2)

# __file__-relative (not host-path-hardcoded -- see usb_assembly_tasks_cfg.py's identical
# fix for why that matters inside a container). Generated by
# manifeel_isaaclab/author_elastomer_link.py -- a local copy of AutoMate's stock
# franka_mimic.usd with an added elastomer_right rigid-body link (fixed-jointed to
# panda_rightfinger, carrying the converted GelSight gelpad mesh). Needed because
# isaaclab_contrib's VisuoTactileSensor requires its parent prim to be a genuine PhysX
# rigid body (create_rigid_body_view(), not just visual geometry) -- franka_mimic.usd
# has no such link at all, and there's no supported API to add one to an
# already-built/remote-hosted USD asset at the Python scene-cfg layer alone.
_REPO_ROOT = pathlib.Path(__file__).resolve().parents[3]
_FRANKA_WITH_ELASTOMER_USD = str(_REPO_ROOT / "assets" / "industreal" / "usd" / "franka_mimic_with_elastomer.usd")


@configclass
class UsbAssemblySceneCfg(AssemblySceneCfg):
    """AutoMate assembly scene plus a wrist camera on the Franka hand."""

    wrist_camera: CameraCfg = CameraCfg(
        prim_path="{ENV_REGEX_NS}/Robot/panda_hand/wrist_camera",
        offset=CameraCfg.OffsetCfg(
            pos=(0.045, 0.0, 0.04),
            rot=(0.5, 0.0, 0.866, 0.0),  # xyzw, ported from TacSLTaskUSB.yaml camera_pose
            # IsaacGym Preview's attach_camera_to_body forward axis is +X -- matches Isaac
            # Lab's "world" convention (fwd=+X, up=+Z), not the default "ros" (fwd=+Z, up=-Y).
            convention="world",
        ),
        width=256,
        height=256,
        data_types=["rgb"],
        spawn=sim_utils.PinholeCameraCfg(
            focal_length=_FOCAL_LENGTH,
            horizontal_aperture=_HORIZONTAL_APERTURE,
            clipping_range=(0.01, 10.0),
        ),
    )

    # Per-finger grasp/insertion contact force, filtered against the held USB plug so
    # net_normal_forces_w / normal_force_matrix_w isolate plug contact from table/socket
    # contact. filter_prim_paths_expr requires prim_path to match exactly one body per
    # env, so this is two sensors (one per finger) rather than a single wildcard sensor.
    left_finger_contact: ContactSensorCfg = ContactSensorCfg(
        prim_path="{ENV_REGEX_NS}/Robot/panda_leftfinger",
        update_period=0.0,
        history_length=1,
        filter_prim_paths_expr=["{ENV_REGEX_NS}/HeldAsset/Geometry/USB_plug/manifeel_usb_plug"],
    )
    right_finger_contact: ContactSensorCfg = ContactSensorCfg(
        prim_path="{ENV_REGEX_NS}/Robot/panda_rightfinger",
        update_period=0.0,
        history_length=1,
        filter_prim_paths_expr=["{ENV_REGEX_NS}/HeldAsset/Geometry/USB_plug/manifeel_usb_plug"],
    )

    # World-fixed (not robot-attached) camera, matching TacSLTaskUSB.yaml's "front"
    # entry: is_body_camera=False, camera_pose=[[0.68, 0, 0.15], [-0.258819045,
    # 1.58480958e-17, 0.965925826, 5.91458986e-17]]. The original IsaacGym code
    # constructs the identical gymapi.Transform(Vec3(pos), Quat(quat)) for both body
    # and non-body cameras (set_camera_transform vs attach_camera_to_body -- see
    # tacsl_sensors.py:217-233), so the same "world" convention/forward-axis reasoning
    # used for wrist_camera above applies here too -- not a separate derivation.
    front_camera: CameraCfg = CameraCfg(
        prim_path="{ENV_REGEX_NS}/front_camera",
        offset=CameraCfg.OffsetCfg(
            pos=(0.68, 0.0, 0.15),
            rot=(-0.258819045, 1.58480958e-17, 0.965925826, 5.91458986e-17),  # xyzw
            convention="world",
        ),
        width=256,
        height=256,
        data_types=["rgb"],
        spawn=sim_utils.PinholeCameraCfg(
            focal_length=_FOCAL_LENGTH,
            horizontal_aperture=_HORIZONTAL_APERTURE,
            clipping_range=(0.01, 10.0),
        ),
    )

    # Force-field tactile sensor on the right fingertip, via Isaac Lab's official TacSL
    # port (isaaclab_contrib.sensors.tacsl_sensor) -- parameters below are a direct port
    # of the original IsaacGym TacSL constants/config, not independently chosen:
    #   tactile_kn=1.0 -> normal_contact_stiffness, tactile_mu=2.0 -> friction_coefficient,
    #   tactile_kt=0.1 -> tangential_stiffness (manifeel-isaacgymenvs/isaacgymenvs/
    #   tacsl_sensors/tacsl_sensors.py:374-377); tactile_array_size=(10,14) matches
    #   TacSLTaskUSB.yaml's tactile_force_field_right shape [10,14,3]; tactile_margin
    #   is tacsl_sensors.py's generate_tactile_points() default. enable_camera_tactile
    #   is off since the trained policy only consumes the force field, not taxim
    #   RGB/depth. prim_path's PARENT is elastomer_right -- a real rigid-body link
    #   authored directly into _FRANKA_WITH_ELASTOMER_USD (see __post_init__ below and
    #   author_elastomer_link.py), not a separate Python-side asset here. Pointing at
    #   panda_rightfinger directly would both match the finger's own bare mesh instead
    #   of this gelpad (ambiguous USD child traversal order) AND fail
    #   _create_physx_views(), which needs its own dedicated rigid-body view for
    #   whatever prim this points at.
    right_tactile_sensor: VisuoTactileSensorCfg = VisuoTactileSensorCfg(
        prim_path="{ENV_REGEX_NS}/Robot/panda_rightfinger/elastomer_right/tactile_sensor",
        # render_cfg has no default and is required by configclass validation even
        # with enable_camera_tactile=False (it's just never exercised in that case) --
        # GELSIGHT_R15_CFG is the predefined config VisuoTactileSensorCfg's own
        # docstring example uses for this.
        render_cfg=GELSIGHT_R15_CFG,
        enable_camera_tactile=False,
        enable_force_field=True,
        tactile_array_size=(10, 14),
        tactile_margin=0.003,
        normal_contact_stiffness=1.0,
        friction_coefficient=2.0,
        tangential_stiffness=0.1,
        contact_object_prim_path_expr="{ENV_REGEX_NS}/HeldAsset/Geometry/USB_plug/manifeel_usb_plug",
        camera_cfg=None,
    )

    def __post_init__(self):
        super().__post_init__()
        # AssemblySceneCfg's franka_mimic.usd spawn has this off; PhysX only reports
        # contacts for bodies on an articulation spawned with it enabled.
        self.robot.spawn.activate_contact_sensors = True
        # Local copy with the added elastomer_right link (see author_elastomer_link.py)
        # instead of AssemblySceneCfg's stock remote franka_mimic.usd -- same asset
        # otherwise, this is strictly additive.
        self.robot.spawn.usd_path = _FRANKA_WITH_ELASTOMER_USD


@configclass
class UsbInsertionEnvCfg(AssemblyEnvCfg):
    """Env config for the USB plug/socket insertion task."""

    task_name: str = "usb_insertion"
    tasks: dict = {"usb_insertion": UsbInsertion()}

    scene: UsbAssemblySceneCfg = UsbAssemblySceneCfg(num_envs=128, env_spacing=2.0)

    # TacSLTaskUSB.yaml's randomize.franka_arm_initial_dof_pos -- the Franka arm config
    # _reset_idx resets to via _set_franka_to_default_pose(joints=self.cfg.ctrl.reset_joints)
    # before UsbInsertionEnv.randomize_initial_state() moves it to the grasp-approach pose.
    ctrl: CtrlCfg = CtrlCfg(
        reset_joints=[0.0002, -0.1591, 0.0005, -2.0966, -0.0002, 1.9335, 0.7855],
    )
